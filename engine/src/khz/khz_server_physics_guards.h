// Intentionally declare the lease in the FUNCTION scope. A do/while block
// would release it before the native effect and reopen the capture race.
#define KHZ_SERVER_PHYSICS_GUARD_VOID(site) KHZ_ServerPhysicsEntry khzPhysicsEntry(khz::server_physics_guard::Site::site); if (!khzPhysicsEntry.allowed()) return
#define KHZ_SERVER_PHYSICS_GUARD_VALUE(site, value) KHZ_ServerPhysicsEntry khzPhysicsEntry(khz::server_physics_guard::Site::site); if (!khzPhysicsEntry.allowed()) return (value)
#define KHZ_SERVER_PHYSICS_GUARD_FATAL(site) KHZ_ServerPhysicsEntry khzPhysicsEntry(khz::server_physics_guard::Site::site); if (!khzPhysicsEntry.allowed()) KHZ_ServerPhysicsFatalRejection(khz::server_physics_guard::Site::site)
#else
#define KHZ_SERVER_PHYSICS_GUARD_VOID(site) do { } while (0)
#define KHZ_SERVER_PHYSICS_GUARD_VALUE(site, value) do { } while (0)
#define KHZ_SERVER_PHYSICS_GUARD_FATAL(site) do { } while (0)
#endif


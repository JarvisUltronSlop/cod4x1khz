"""Regenerate project-owned COM ABI bases from the installed Windows SDK.

Only interface signatures are read. Unsupported methods return explicit failure;
these bases are not a capability claim and do not emulate rendering through DX9.
The generated header is checked in, so ordinary builds need no generator step.
"""
import argparse
import re
from pathlib import Path

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('header',type=Path)
    args=p.parse_args()
    source=args.header.read_text()
    names=['IDirect3D9','IDirect3DDevice9','IDirect3DVertexBuffer9','IDirect3DIndexBuffer9',
           'IDirect3DTexture9','IDirect3DCubeTexture9','IDirect3DVolumeTexture9',
           'IDirect3DSurface9','IDirect3DVolume9','IDirect3DVertexShader9',
           'IDirect3DPixelShader9','IDirect3DVertexDeclaration9','IDirect3DQuery9','IDirect3DSwapChain9']
    out=['// Generated by scripts/generate_legacy_interfaces.py; do not edit signatures.',
         '#pragma once','#define WIN32_LEAN_AND_MEAN','#define NOMINMAX','#include <d3d9.h>','#include <atomic>',
         'namespace gfx::legacy {',
         'HRESULT unsupported(const char* method);',
         'template<class T> class Object : public T {',
         'protected: std::atomic<ULONG> references{1}; virtual ~Object() = default;',
         'public: HRESULT STDMETHODCALLTYPE QueryInterface(REFIID id,void** result) override {',
         'if(!result) return E_POINTER; *result=nullptr;',
         'if(id!=__uuidof(IUnknown)&&id!=__uuidof(T)) return E_NOINTERFACE;',
         '*result=static_cast<T*>(this);AddRef();return S_OK;}',
         'ULONG STDMETHODCALLTYPE AddRef() override {return ++references;}',
         'ULONG STDMETHODCALLTYPE Release() override {const auto n=--references;if(!n) delete this;return n;}',
         '};']
    for name in names:
        body=re.search(r'DECLARE_INTERFACE_\('+name+r',\s*\w+\)\s*\{(.*?)\n\};',source,re.S).group(1)
        out.append(f'class {name}Base : public Object<{name}> {{ public:')
        methods=re.findall(r'STDMETHOD(_?)\(([^)]+)\)\((.*?)\)\s*PURE;',body,re.S)
        for explicit,method,arguments in methods:
            ret,method=map(str.strip,method.split(',',1)) if explicit else ('HRESULT',method)
            if method in ('QueryInterface','AddRef','Release'): continue
            arguments=re.sub(r'\bTHIS_?\b','',arguments).strip()
            arguments=' '.join(arguments.split())
            call=f'unsupported("{name}::{method}")'
            result=f'return {call};' if ret=='HRESULT' else call+';'+('' if ret=='void' else 'return {};')
            out.append(f'{ret} STDMETHODCALLTYPE {method}({arguments}) override {{{result}}}')
        out.append('};')
    out.append('}')
    path=Path(__file__).resolve().parent.parent/'engine/src/gfx/legacy_interfaces.h'
    path.write_text('\n'.join(out)+'\n')
    print(f'Generated {len(names)} interface bases in {path}')

if __name__=='__main__':main()
